CREATE TABLE IF NOT EXISTS game.forum_images (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,post_id BIGINT NOT NULL REFERENCES game.forum_posts(id),jpeg_base64 TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS game.forum_comments (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,post_id BIGINT NOT NULL REFERENCES game.forum_posts(id),user_id BIGINT NOT NULL REFERENCES game.users(id),display_name TEXT NOT NULL,body TEXT NOT NULL,created DOUBLE PRECISION NOT NULL);
