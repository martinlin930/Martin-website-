-- App data stays outside Supabase's public Data API schema.
CREATE SCHEMA IF NOT EXISTS game;
CREATE TABLE IF NOT EXISTS game.users (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username TEXT UNIQUE NOT NULL, password_hash TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS game.login_attempts (username TEXT PRIMARY KEY, failures INTEGER NOT NULL, last_attempt BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS game.players (id TEXT PRIMARY KEY, nickname TEXT NOT NULL, x DOUBLE PRECISION NOT NULL, z DOUBLE PRECISION NOT NULL, updated DOUBLE PRECISION NOT NULL, yaw DOUBLE PRECISION NOT NULL DEFAULT 0, jump DOUBLE PRECISION NOT NULL DEFAULT 0, running INTEGER NOT NULL DEFAULT 0, avatar TEXT NOT NULL DEFAULT '01m', user_id BIGINT REFERENCES game.users(id));
CREATE TABLE IF NOT EXISTS game.game_saves (user_id BIGINT PRIMARY KEY REFERENCES game.users(id), nickname TEXT NOT NULL, avatar TEXT NOT NULL, x DOUBLE PRECISION NOT NULL, z DOUBLE PRECISION NOT NULL, yaw DOUBLE PRECISION NOT NULL, pitch DOUBLE PRECISION NOT NULL DEFAULT 0, music_muted INTEGER NOT NULL DEFAULT 0, updated DOUBLE PRECISION NOT NULL, save_version INTEGER NOT NULL DEFAULT 1);
CREATE TABLE IF NOT EXISTS game.messages (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nickname TEXT NOT NULL, body TEXT NOT NULL, created DOUBLE PRECISION NOT NULL);
CREATE INDEX IF NOT EXISTS players_updated_idx ON game.players(updated);
CREATE INDEX IF NOT EXISTS players_user_idx ON game.players(user_id);
ALTER TABLE game.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE game.login_attempts ENABLE ROW LEVEL SECURITY;
ALTER TABLE game.players ENABLE ROW LEVEL SECURITY;
ALTER TABLE game.game_saves ENABLE ROW LEVEL SECURITY;
ALTER TABLE game.messages ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON SCHEMA game FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL TABLES IN SCHEMA game FROM PUBLIC, anon, authenticated;

